<?php
/**
 * Assemble deployable directories from one commit and one merchant config. No secrets, network or upload.
 *
 *   php scripts/heartshop/release.php OUT_DIR
 *
 * OUT_DIR/shop/   contents of the shop directory, deployed to <web root><base>/
 * OUT_DIR/panel/  (only with shop.panel_origins) the panel host's document root
 * OUT_DIR/root/   (only with mount 'root') the web-root files: .htaccess, robots.txt, sitemap.xml
 *
 * Every tree carries the same api/release-id.php so a deployment can prove shop and panel match.
 * Copying the trees to a server is a separate, explicitly authorized operator step.
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') exit(1);
$root = dirname(__DIR__, 2);
$out = $argv[1] ?? '';
if ($out === '' || str_starts_with($out, '-')) { fwrite(STDERR, "Usage: php release.php OUT_DIR\n"); exit(2); }

passthru(escapeshellarg(PHP_BINARY).' '.escapeshellarg(__DIR__.'/build-storefront.php').' --check', $code);
if ($code !== 0) { fwrite(STDERR, "Refusing to release a stale storefront build.\n"); exit(1); }

require __DIR__.'/layout.php';
$c = layoutConfig($root);
$separate = panelSeparate();
$mounted = ($c['shop']['mount'] ?? 'root') === 'subdirectory';
$shopDir = $root.'/public/heartshop';

// Shop and panel must read one private .env and one database: the path cannot depend on where a tree is copied.
$env = (string)$c['env_file'];
if ($separate && (!str_starts_with($env, '/') || str_starts_with($env, $root.'/'))) {
    fwrite(STDERR, "With a separate panel host, set env_file in config.php to an absolute private path outside every web root.\n");
    exit(1);
}

if (file_exists($out) && (!is_dir($out) || count(scandir($out)) > 2)) { fwrite(STDERR, "OUT_DIR must be new or empty.\n"); exit(1); }
umask(0022);

/** Relative paths of deployable files: no dotfiles except .htaccess, no editor or OS clutter. */
function deployable(string $dir): array {
    $files = [];
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $file) {
        if ($file->isLink()) throw new RuntimeException('Symlinks are not released: '.$file->getPathname());
        if (!$file->isFile()) continue;
        $relative = substr($file->getPathname(), strlen($dir) + 1);
        $name = basename($relative);
        $hiddenDir = preg_match('#(^|/)\.#', dirname($relative)) && dirname($relative) !== '.';
        if ($hiddenDir || ($name !== '.htaccess' && str_starts_with($name, '.'))) continue;
        if (preg_match('/(~|\.swp|\.bak|\.orig)$/', $name)) continue;
        $files[] = $relative;
    }
    sort($files);
    return $files;
}

function put(string $path, string $content): void {
    if (!is_dir(dirname($path))) mkdir(dirname($path), 0755, true);
    file_put_contents($path, $content);
    chmod($path, 0644);
}

$all = deployable($shopDir);
$panelEntry = ['api/panel.php'];
$shopOnly = ['api/order.php', 'api/status.php', 'api/webhook.php'];
$trees = [];
$trees['shop'] = array_fill_keys(array_values(array_filter($all, fn($f) =>
    !$separate || (!str_starts_with($f, 'panel/') && !in_array($f, $panelEntry, true)))), null);
if ($separate) {
    $panel = array_values(array_filter($all, fn($f) => $f === 'panel/index.html' || str_starts_with($f, 'assets/')
        || (str_starts_with($f, 'api/') && !in_array($f, $shopOnly, true))));
    $trees['panel'] = array_fill_keys($panel, null);
    $template = file_get_contents($root.'/config/panel-host.htaccess');
    $template = replaceGenerated($template, 'HOSTS', hostRules($c['shop']['panel_origins'], 'panel'));
    $trees['panel']['.htaccess'] = replaceGenerated($template, 'ENTRY POINTS', entryPointRule(['panel']));
}
if (!$mounted) {
    foreach (['.htaccess', 'robots.txt', 'sitemap.xml'] as $f) $trees['root'][$f] = file_get_contents($root.'/public/'.$f);
}

// One identifier for the whole release: code revision plus the exact bytes of every released file.
$commit = trim((string)shell_exec('git -C '.escapeshellarg($root).' rev-parse HEAD 2>/dev/null')) ?: 'unknown';
$dirty = trim((string)shell_exec('git -C '.escapeshellarg($root).' status --porcelain 2>/dev/null')) !== '';
$digest = hash_init('sha256');
foreach ($trees as $name => $files) {
    foreach ($files as $f => $content) {
        hash_update($digest, "$name/$f\0".hash('sha256', $content ?? file_get_contents("$shopDir/$f"))."\n");
    }
}
$id = substr(hash_final($digest), 0, 16);
$stamp = "<?php\n// Generated by scripts/heartshop/release.php; not an entry point.\nreturn ".var_export(
    ['release' => $id, 'commit' => $commit, 'local_changes' => $dirty, 'base' => $c['shop']['base']], true).";\n";

foreach ($trees as $name => $files) {
    foreach ($files as $f => $content) put("$out/$name/$f", $content ?? file_get_contents("$shopDir/$f"));
    if ($name !== 'root') put("$out/$name/api/release-id.php", $stamp);
}
echo "PASS release $id ($commit".($dirty ? ', with local changes' : '').'): '.implode(', ', array_keys($trees))."\n";
echo 'Deploy shop/ to <web root>'.$c['shop']['base']."/".($separate ? ' and panel/ to the panel document root, from this same OUT_DIR' : '')."\n";
